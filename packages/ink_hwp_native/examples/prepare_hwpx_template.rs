use serde_json::json;
use sha2::{Digest, Sha256};
use std::{env, fs, io::Read, path::PathBuf};

const MARKER: &str = "PIV_HWPX_TITLE_MARKER";
const UPSTREAM: &str = "4e6e8c2a61694899e37b4f7c2f97523153a623b9";

fn dart_literal(value: &str) -> String {
    let mut result = String::from("'");
    for character in value.chars() {
        match character {
            '\\' => result.push_str("\\\\"),
            '\'' => result.push_str("\\'"),
            '$' => result.push_str("\\$"),
            '\n' => result.push_str("\\n"),
            '\r' => result.push_str("\\r"),
            '\t' => result.push_str("\\t"),
            other => result.push(other),
        }
    }
    result.push('\'');
    result
}

fn main() {
    let output = PathBuf::from(env::args().nth(1).expect("output directory"));
    fs::create_dir_all(&output).unwrap();
    let source = output.join("writer-skeleton.hwpx");
    let mut document = hwp_convert::from_markdown(MARKER);
    document.metadata.title = Some(MARKER.into());
    document.metadata.author = Some("Personal Ink Vault".into());
    document.metadata.last_saved_by = Some("Personal Ink Vault".into());
    let report = hwpx::write_document_with_report(&document, &source).unwrap();
    assert!(report.preservation.is_lossless(), "{report:?}");
    let reopened = hwpx::read_document(&source).unwrap();
    assert_eq!(reopened.document.sections.len(), 1);
    assert_eq!(reopened.document.sections[0].paragraphs.len(), 1);

    let mut archive = zip::ZipArchive::new(fs::File::open(&source).unwrap()).unwrap();
    let mut parts = Vec::new();
    let mut dart = format!(
        "// Generated by packages/ink_hwp_native/examples/prepare_hwpx_template.rs.\n\
         // hwp-cli {UPSTREAM}; this is a generated document, not copied engine code.\n\
         const hwpxTemplateMarker = '{MARKER}';\n\
         const hwpxTemplateParts = <String, String>{{\n"
    );
    let mut marker_count = 0;
    for index in 0..archive.len() {
        let mut entry = archive.by_index(index).unwrap();
        if index == 0 {
            assert_eq!(entry.name(), "mimetype");
            assert_eq!(entry.compression(), zip::CompressionMethod::Stored);
        }
        let mut value = String::new();
        entry.read_to_string(&mut value).unwrap();
        marker_count += value.matches(MARKER).count();
        let name = entry.name().to_string();
        dart.push_str(&format!("  {}:\n", dart_literal(&name)));
        let mut segments = value.split_inclusive('>').peekable();
        while let Some(segment) = segments.next() {
            dart.push_str(&format!(
                "    {}{}\n",
                dart_literal(segment),
                if segments.peek().is_none() { "," } else { "" }
            ));
        }
        parts.push(json!({"name":name,"bytes":value.len(),"text":value}));
    }
    assert_eq!(marker_count, 3);
    dart.push_str("};\n");
    fs::write(output.join("hwpx_template_parts.dart"), dart).unwrap();
    fs::write(
        output.join("template-parts.json"),
        serde_json::to_string_pretty(&parts).unwrap(),
    )
    .unwrap();
    let bytes = fs::read(&source).unwrap();
    let hash: String = Sha256::digest(&bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect();
    fs::write(
        output.join("provenance.json"),
        serde_json::to_string_pretty(&json!({
            "upstreamCommit":UPSTREAM,"writer":"hwpx::write_document_with_report",
            "documentFactory":"hwp_convert::from_markdown with fixed literal marker",
            "skeletonSha256":hash,"skeletonBytes":bytes.len(),
            "entries":parts.len(),"markerOccurrences":marker_count,
            "readBackSections":1,"readBackParagraphs":1,
            "writerReport":format!("{report:?}"),
        }))
        .unwrap(),
    )
    .unwrap();
    println!("Generated and reopened {} HWPX template parts", parts.len());
}
