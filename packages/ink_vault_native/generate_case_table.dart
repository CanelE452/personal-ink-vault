import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';

void main(List<String> arguments) {
  final crate = File.fromUri(Platform.script).parent;
  final sdk = File(Platform.resolvedExecutable).parent.parent;
  final version = File('${sdk.path}/version').readAsStringSync().trim();
  if (version != '3.13.5') {
    throw StateError('Use the pinned Dart 3.13.5 VM to regenerate this table.');
  }
  final lower = <(int, int)>[], upper = <(int, int)>[];
  var scalarCount = 0;
  for (var scalar = 0; scalar <= 0x10ffff; scalar++) {
    if (scalar >= 0xd800 && scalar <= 0xdfff) continue;
    final value = String.fromCharCode(scalar);
    final lowerRunes = value.toLowerCase().runes.toList(growable: false);
    final upperRunes = value.toUpperCase().runes.toList(growable: false);
    if (lowerRunes.length != 1 || upperRunes.length != 1) {
      throw StateError('A mapping expands scalar $scalar');
    }
    if (lowerRunes.single != scalar) lower.add((scalar, lowerRunes.single));
    if (upperRunes.single != scalar) upper.add((scalar, upperRunes.single));
    scalarCount++;
  }
  final source = StringBuffer()
    ..writeln(
      '// Generated by generate_case_table.dart with the Dart 3.13.5 VM.',
    )
    ..writeln('// Observed String case mappings; see DART_SDK_LICENSE.txt and')
    ..writeln(
      '// tests/fixtures/dart_case_table_provenance.json. Do not edit by hand.',
    )
    ..writeln();
  for (final (name, table) in [('LOWER', lower), ('UPPER', upper)]) {
    source.writeln('pub(crate) const $name: &[(u32, u32)] = &[');
    for (final (before, after) in table) {
      source.writeln('    ($before, $after),');
    }
    source.writeln('];\n');
  }
  final generated = File('${crate.path}/src/workspace_query_case_table.rs');
  final license = File('${sdk.path}/LICENSE').readAsBytesSync();
  final notice = File('${crate.path}/DART_SDK_LICENSE.txt');
  final output = '${source.toString().trimRight()}\n';
  if (arguments.contains('--check')) {
    if (!generated.existsSync() ||
        generated.readAsStringSync() != output ||
        !notice.existsSync() ||
        sha256.convert(notice.readAsBytesSync()).toString() !=
            sha256.convert(license).toString()) {
      throw StateError('Generated case table or SDK notice does not match.');
    }
  } else {
    generated.writeAsStringSync(output);
    notice.writeAsBytesSync(license);
    final revision = File('${sdk.path}/revision');
    final provenance = {
      'schemaVersion': 1,
      'method': 'Observed Dart VM String.toLowerCase and String.toUpperCase for every Unicode scalar; no application source was extracted.',
      'sdkVersion': version,
      'sdkRevision': revision.existsSync()
          ? revision.readAsStringSync().trim()
          : null,
      'runtimeVersion': Platform.version,
      'sdkExecutableName': File(Platform.resolvedExecutable)
          .uri
          .pathSegments
          .last,
      'sdkExecutableSha256': sha256
          .convert(File(Platform.resolvedExecutable).readAsBytesSync())
          .toString(),
      'generatorSha256': sha256
          .convert(File.fromUri(Platform.script).readAsBytesSync())
          .toString(),
      'scalarCount': scalarCount,
      'lowerMappings': lower.length,
      'upperMappings': upper.length,
      'expandingMappings': 0,
      'tableSha256': sha256.convert(utf8.encode(output)).toString(),
      'sdkLicenseSha256': sha256.convert(license).toString(),
      'unpairedSurrogates': 'Preserve unchanged in the UTF-16 query VM; they are not Unicode scalars.',
    };
    final metadata = File(
      '${crate.path}/tests/fixtures/dart_case_table_provenance.json',
    );
    metadata.parent.createSync(recursive: true);
    metadata.writeAsStringSync(
      '${const JsonEncoder.withIndent('  ').convert(provenance)}\n',
    );
  }
  stdout.writeln(
    'Verified $scalarCount scalars; lower=${lower.length}, upper=${upper.length}, expanding=0.',
  );
}
